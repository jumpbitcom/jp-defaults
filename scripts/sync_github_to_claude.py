#!/usr/bin/env python3
"""
sync_github_to_claude.py - make Claude Code use a repo's GitHub Copilot customizations.

Maps (source -> target):
   .github/copilot-instructions.md            -> @import in CLAUDE.md (managed block)
   AGENTS.md (repo root)                      -> @import in CLAUDE.md (managed block)
   .github/instructions/**/*.instructions.md  -> .claude/rules/github/**.md   (applyTo -> paths)
   .github/skills/<name>/                     -> .claude/skills/<name>        (symlink, copy fallback)
   .github/agents/*.agent.md                  -> .claude/agents/<name>.md     (tools mapped best-effort)
   .github/prompts/*.prompt.md                -> .claude/skills/<name>/SKILL.md (user-invoked /name)

Usage:
   python3 sync_github_to_claude.py [repo_root] [--check] [--copy-skills]
      --check        report drift, change nothing, exit 1 if out of date (for CI / pre-commit)
      --copy-skills  copy skill folders instead of symlinking (Windows clones without core.symlinks)

Stdlib only. Idempotent. Generated files carry a marker; stale ones are removed on the next run.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
from pathlib import Path

MARK = "<!-- generated by sync_github_to_claude.py from {src} - edit the source, not this file -->"
MARK_RE = re.compile(r"<!-- generated by sync_github_to_claude\.py from (.+?) - ")
BLOCK_START = "<!-- BEGIN github-sync (managed) -->"
BLOCK_END = "<!-- END github-sync (managed) -->"

# Copilot custom-agent tool aliases -> Claude Code tool names (best effort; unknown ones are dropped)
TOOL_MAP = {
    "read": ["Read"],
    "edit": ["Edit", "Write"],
    "search": ["Grep", "Glob"],
    "shell": ["Bash"],
    "execute": ["Bash"],
    "bash": ["Bash"],
    "terminal": ["Bash"],
    "web": ["WebFetch", "WebSearch"],
    "fetch": ["WebFetch"],
    "agent": ["Agent"],
    "custom-agent": ["Agent"],
    "todo": ["TodoWrite"],
}

changes: list[str] = []


# ---------- helpers ----------
def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Minimal YAML frontmatter reader: top-level 'key: value' and simple '- item' lists."""
    if not text.startswith("---"):
        return {}, text
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n?", text, re.S)
    if not m:
        return {}, text
    meta: dict[str, str] = {}
    key = None
    for line in m.group(1).splitlines():
        if re.match(r"^\s+-\s+", line) and key:
            item = line.strip()[1:].strip().strip("'\"")
            meta[key] = (meta[key] + "," if meta[key] else "") + item
        elif ":" in line and not line.startswith((" ", "\t")):
            key, val = line.split(":", 1)
            key = key.strip()
            meta[key] = val.strip()
    return meta, text[m.end() :]


def unquote_list(val: str) -> list[str]:
    val = val.strip().strip("[]")
    return [p.strip().strip("'\"") for p in val.split(",") if p.strip().strip("'\"")]


def write_if_changed(path: Path, content: str, check: bool) -> None:
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return
    changes.append(f"write  {path}")
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def generated_source(path: Path) -> str | None:
    try:
        m = MARK_RE.search(path.read_text(encoding="utf-8")[:500])
        return m.group(1) if m else None
    except (OSError, UnicodeDecodeError):
        return None


def yaml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# ---------- 1. CLAUDE.md imports ----------
def sync_claude_md(root: Path, check: bool) -> None:
    imports = []
    if (root / ".github/copilot-instructions.md").is_file():
        imports.append("@.github/copilot-instructions.md")
    if (root / "AGENTS.md").is_file():
        imports.append("@AGENTS.md")
    claude_md = root / (
        "CLAUDE.md"
        if not (root / ".claude/CLAUDE.md").is_file()
        else ".claude/CLAUDE.md"
    )
    if claude_md.name == "CLAUDE.md" and claude_md.parent.name == ".claude":
        imports = [i.replace("@", "@../", 1) for i in imports]  # relative to .claude/
    old = claude_md.read_text(encoding="utf-8") if claude_md.is_file() else ""
    block = (
        "\n".join(
            [
                BLOCK_START,
                "## Shared instructions (also used by GitHub Copilot)",
                *imports,
                BLOCK_END,
            ]
        )
        if imports
        else ""
    )
    pattern = re.compile(re.escape(BLOCK_START) + r".*?" + re.escape(BLOCK_END), re.S)
    if pattern.search(old):
        new = pattern.sub(block, old) if block else pattern.sub("", old).strip() + "\n"
    elif block:
        new = block + "\n\n" + old if old else block + "\n"
    else:
        return
    write_if_changed(claude_md, new, check)


# ---------- 2. path-specific instructions -> rules ----------
def sync_instructions(root: Path, check: bool, produced: set[Path]) -> None:
    src_dir = root / ".github/instructions"
    if not src_dir.is_dir():
        return
    for src in sorted(src_dir.rglob("*.instructions.md")):
        meta, body = split_frontmatter(src.read_text(encoding="utf-8"))
        if meta.get("excludeAgent", "").strip("'\"") == "cloud-agent":
            continue  # author scoped it to code review only
        rel = (
            src.relative_to(src_dir).as_posix().removesuffix(".instructions.md") + ".md"
        )
        dst = root / ".claude/rules/github" / rel
        globs = unquote_list(meta.get("applyTo", ""))
        fm = ""
        if globs and not set(globs) <= {"**", "**/*", "*"}:
            fm = (
                "---\npaths:\n"
                + "".join(f"  - {yaml_str(g)}\n" for g in globs)
                + "---\n"
            )
        content = (
            fm
            + MARK.format(src=src.relative_to(root).as_posix())
            + "\n\n"
            + body.lstrip()
        )
        write_if_changed(dst, content, check)
        produced.add(dst.resolve())


# ---------- 3. skills ----------
def sync_skills(root: Path, check: bool, copy: bool) -> None:
    src_dir = root / ".github/skills"
    if not src_dir.is_dir():
        return
    dst_dir = root / ".claude/skills"
    for skill in sorted(p for p in src_dir.iterdir() if (p / "SKILL.md").is_file()):
        dst = dst_dir / skill.name
        target = os.path.relpath(skill, dst_dir)
        if dst.is_symlink():
            if os.readlink(dst) == target:
                continue
        elif dst.exists():
            if not (dst / ".github-sync").is_file():
                print(
                    f"skip   {dst} (exists and is not managed by this script)",
                    file=sys.stderr,
                )
                continue
            if copy:  # managed copy: refresh
                changes.append(f"copy   {skill} -> {dst}")
                if not check:
                    shutil.rmtree(dst)
                    shutil.copytree(skill, dst)
                    (dst / ".github-sync").write_text(
                        f"source: {skill.relative_to(root).as_posix()}\n"
                    )
                continue
        changes.append(
            f"{'copy' if copy else 'link'}   {dst} -> {skill.relative_to(root)}"
        )
        if check:
            continue
        dst_dir.mkdir(parents=True, exist_ok=True)
        if dst.is_symlink() or dst.exists():
            dst.unlink() if dst.is_symlink() else shutil.rmtree(dst)
        try:
            if copy:
                raise OSError("copy requested")
            os.symlink(target, dst, target_is_directory=True)
        except OSError:
            shutil.copytree(skill, dst)
            (dst / ".github-sync").write_text(
                f"source: {skill.relative_to(root).as_posix()}\n"
            )


# ---------- 4. custom agents -> subagents ----------
def sync_agents(root: Path, check: bool, produced: set[Path]) -> None:
    src_dir = root / ".github/agents"
    if not src_dir.is_dir():
        return
    for src in sorted(src_dir.glob("*.md")):
        meta, body = split_frontmatter(src.read_text(encoding="utf-8"))
        stem = src.name.removesuffix(".agent.md").removesuffix(".md")
        name = meta.get("name", "").strip("'\"") or stem
        desc = (
            meta.get("description", "").strip("'\"")
            or f"Custom agent '{name}' imported from GitHub Copilot."
        )
        tools: list[str] = []
        for t in unquote_list(meta.get("tools", "")):
            for mapped in TOOL_MAP.get(t.lower().split("/")[-1], []):
                if mapped not in tools:
                    tools.append(mapped)
        fm = f"---\nname: {name}\ndescription: {yaml_str(desc)}\n"
        if tools:  # no tools key = inherit all tools
            fm += f"tools: {', '.join(tools)}\n"
        fm += "---\n"
        dst = root / ".claude/agents" / f"{name}.md"
        content = (
            fm
            + MARK.format(src=src.relative_to(root).as_posix())
            + "\n\n"
            + body.lstrip()
        )
        write_if_changed(dst, content, check)
        produced.add(dst.resolve())


# ---------- 5. prompt files -> user-invoked skills ----------
def sync_prompts(root: Path, check: bool, produced: set[Path]) -> None:
    src_dir = root / ".github/prompts"
    if not src_dir.is_dir():
        return
    for src in sorted(src_dir.glob("*.prompt.md")):
        meta, body = split_frontmatter(src.read_text(encoding="utf-8"))
        name = meta.get("name", "").strip("'\"") or src.name.removesuffix(".prompt.md")
        desc = (
            meta.get("description", "").strip("'\"")
            or f"Prompt '{name}' imported from GitHub Copilot."
        )
        body = re.sub(
            r"\$\{input:[^}]*\}", "$ARGUMENTS", body
        )  # ${input:x[:placeholder]}
        body = re.sub(
            r"\[([^\]]*)\]\((\.\./[^)]+)\)",  # relative links -> repo paths
            lambda m: (
                f"[{m.group(1)}](@{(src.parent / m.group(2)).resolve().relative_to(root.resolve()).as_posix()})"
                if (src.parent / m.group(2)).resolve().is_relative_to(root.resolve())
                else m.group(0)
            ),
            body,
        )
        dst = root / ".claude/skills" / name / "SKILL.md"
        if dst.parent.exists() and not dst.is_file():
            print(f"skip   {dst.parent} (exists, not a prompt import)", file=sys.stderr)
            continue
        if dst.is_file() and generated_source(dst) is None:
            print(f"skip   {dst} (hand-written skill with same name)", file=sys.stderr)
            continue
        fm = (
            f"---\nname: {name}\ndescription: {yaml_str(desc)}\n"
            f"disable-model-invocation: true\n---\n"
        )
        content = (
            fm
            + MARK.format(src=src.relative_to(root).as_posix())
            + "\n\n"
            + body.lstrip()
        )
        write_if_changed(dst, content, check)
        produced.add(dst.resolve())


# ---------- cleanup of stale generated files ----------
def cleanup(root: Path, check: bool, produced: set[Path]) -> None:
    for base in (".claude/rules/github", ".claude/agents", ".claude/skills"):
        d = root / base
        if not d.is_dir():
            continue
        for f in d.rglob("*.md"):
            if f.is_symlink() or any(
                p.is_symlink() for p in f.parents if p != d and d in p.parents
            ):
                continue
            if generated_source(f) and f.resolve() not in produced:
                changes.append(f"remove {f} (source gone)")
                if not check:
                    f.unlink()
                    if f.name == "SKILL.md" and not any(f.parent.iterdir()):
                        f.parent.rmdir()
    sk = root / ".claude/skills"
    if sk.is_dir():
        for link in sk.iterdir():
            if (
                link.is_symlink()
                and ".github/skills" in os.readlink(link)
                and not link.exists()
            ):
                changes.append(f"remove {link} (dangling link)")
                if not check:
                    link.unlink()


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("root", nargs="?", default=".")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--copy-skills", action="store_true")
    a = ap.parse_args()
    root = Path(a.root).resolve()
    if not (root / ".github").is_dir() and not (root / "AGENTS.md").is_file():
        print(f"No .github/ or AGENTS.md in {root}", file=sys.stderr)
        return 2
    produced: set[Path] = set()
    sync_claude_md(root, a.check)
    sync_instructions(root, a.check, produced)
    sync_skills(root, a.check, a.copy_skills)
    sync_agents(root, a.check, produced)
    sync_prompts(root, a.check, produced)
    cleanup(root, a.check, produced)
    for c in changes:
        print(("would " if a.check else "") + c)
    if not changes:
        print("Claude Code config is in sync with .github/")
    return 1 if (a.check and changes) else 0


if __name__ == "__main__":
    sys.exit(main())
